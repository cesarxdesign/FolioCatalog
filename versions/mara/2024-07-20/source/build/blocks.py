def sh(pr,pb,R=5):
    cs=[((np.roll(pb,-d)-pr)**2)[R+1:-R-1].sum() for d in range(-R,R+1)]
    i=int(np.argmin(cs))
    if 0<i<2*R: a,b,c=cs[i-1],cs[i],cs[i+1]; den=(a-2*b+c); return i-R+(0.5*(a-c)/den if den else 0)
    return i-R
